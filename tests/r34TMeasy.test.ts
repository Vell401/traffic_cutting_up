import { describe, expect, it } from 'vitest';
import {
  alignmentTorque, evaluateTMeasy, guessPassCar70, loadInterpL, loadInterpQ,
  tmeasyCurve, TMEASY_UPSTREAM_COMMIT,
  type TMeasyAxis, type TMeasyOptions,
} from '../src/sim/r34/chronoTMeasy';

const twoParabolas: TMeasyAxis = { df0: 10000, sm: .2, fm: 1000, ss: 1, fs: 700 };
const cubic: TMeasyAxis = { df0: 10000, sm: .2, fm: 1000, ss: .3, fs: 500 };

describe('pinned Project Chrono TMeasy steady-state port', () => {
  it('records the source revision and exact InterpL/Q equations', () => {
    expect(TMEASY_UPSTREAM_COMMIT).toBe('bdfd07c2edee80361acffbe01df392c36c6d8ef6');
    expect(loadInterpL(1, 100, 180)).toBe(100);
    expect(loadInterpL(2, 100, 180)).toBe(180);
    expect(loadInterpL(.5, 100, 180)).toBe(60);
    expect(loadInterpQ(0, 100, 180)).toBe(0);
    expect(loadInterpQ(1, 100, 180)).toBe(100);
    expect(loadInterpQ(2, 100, 180)).toBe(180);
    expect(loadInterpQ(.5, 100, 180)).toBe(52.5);
    expect(loadInterpQ(3, 100, 180)).toBe(240);
  });

  it('preserves GuessPassCar70Par dimensional coefficients at pn and 2pn', () => {
    const nominal = guessPassCar70(4000, 4000);
    expect(nominal.x).toEqual({ df0: 73496.4, sm: .13913, fm: 4516.8, ss: .66667, fs: 3205.96 });
    expect(nominal.y.df0).toBeCloseTo(63930.4, 9);
    expect(nominal.y.fm).toBeCloseTo(4003.6, 9);
    expect(nominal.y.fs).toBeCloseTo(3334.4, 9);
    expect(nominal.y.sm).toBe(.14852);
    expect(nominal.y.ss).toBe(.96524);
    expect([nominal.nL0, nominal.sq0, nominal.sqe]).toEqual([.178, .16337, .96524]);
    const twice = guessPassCar70(8000, 4000);
    expect(twice.x.df0).toBeCloseTo(155735.2, 9);
    expect(twice.x.fm).toBeCloseTo(8716.8, 9);
    expect(twice.x.fs).toBeCloseTo(6153.36, 9);
    expect(twice.y.df0).toBeCloseTo(102807.2, 9);
    expect(twice.y.fm).toBeCloseTo(7309.36, 9);
    expect(twice.y.fs).toBeCloseTo(6186.88, 9);
    expect(twice.y.sm).toBeCloseTo(.18504, 12);
    expect(twice.y.ss).toBe(1.0714);
    expect([twice.nL0, twice.sq0, twice.sqe]).toEqual([.19, .20355, 1.0714]);
    expect(guessPassCar70(1e6, 4000)).toEqual(guessPassCar70(14000, 4000));
  });

  // These numeric fixtures were evaluated independently using Python's scalar
  // translation of the pinned C++ equations, not generated by this TS module.
  // The synthetic two-parabola axis has a=12500 and sstar=.23; the cubic
  // axis has sstar=.6 > ss=.3, forcing the other upstream branch.
  it.each([
    [.1, 800, 4800],
    [.2, 1000, 0],
    [.215, 997.1875, -375],
    [.23, 988.75, -750],
    [.6, 777.922077922078, -389.6103896103896],
    [1, 700, 0],
    [1.2, 700, 0],
  ])('matches rational/two-parabola/full-sliding values at s=%s', (s, force, derivative) => {
    const result = tmeasyCurve(s, twoParabolas);
    expect(result.force).toBeCloseTo(force, 9);
    expect(result.forceOverSlip).toBeCloseTo(force / s, 9);
    expect(result.derivative).toBeCloseTo(derivative, 8);
  });

  it('matches the cubic fallback and returns its genuinely negative slope', () => {
    expect(tmeasyCurve(.25, cubic).force).toBeCloseTo(750, 10);
    expect(tmeasyCurve(.25, cubic).derivative).toBeCloseTo(-7500, 8);
    expect(tmeasyCurve(.3, cubic).force).toBeCloseTo(500, 10);
    expect(tmeasyCurve(.3, cubic).derivative).toBeCloseTo(0, 8);
  });

  it('has a finite origin limit, odd force, and the upstream minimum stiffness', () => {
    expect(tmeasyCurve(0, twoParabolas)).toEqual({ force: 0, forceOverSlip: 10000, derivative: 10000 });
    expect(tmeasyCurve(.1, { ...twoParabolas, df0: 1 })).toEqual(tmeasyCurve(.1, twoParabolas));
    for (const s of [.001, .1, .215, .6, 1.2]) {
      const positive = tmeasyCurve(s, twoParabolas);
      const negative = tmeasyCurve(-s, twoParabolas);
      expect(negative.force).toBe(-positive.force);
      expect(negative.derivative).toBe(positive.derivative);
      expect(negative.forceOverSlip).toBe(positive.forceOverSlip);
    }
  });

  it('matches analytic curve derivatives to central differences in every branch', () => {
    for (const axis of [twoParabolas, cubic, guessPassCar70(4000, 4000).x, guessPassCar70(8000, 4000).y]) {
      for (const s of [-1.2, -.6, -.25, -.1, 0, .001, .1, .21, .215, .25, .27, .6, 1.2]) {
        const h = 1e-8;
        const finiteDifference = (tmeasyCurve(s + h, axis).force - tmeasyCurve(s - h, axis).force) / (2 * h);
        expect(Math.abs(tmeasyCurve(s, axis).derivative - finiteDifference)).toBeLessThan(.02);
      }
    }
  });

  it('joins adhesion, both parabolas, and full sliding continuously with C1 slopes', () => {
    for (const [axis, joins] of [[twoParabolas, [.2, .23, 1]], [cubic, [.2, .3]]] as const) {
      for (const join of joins) {
        const before = tmeasyCurve(join - 1e-9, axis);
        const after = tmeasyCurve(join + 1e-9, axis);
        expect(Math.abs(after.force - before.force)).toBeLessThan(1e-4);
        expect(Math.abs(after.derivative - before.derivative)).toBeLessThan(.001);
      }
    }
  });

  it.each([
    // q, sx, sy, mu, Fx [N], Fy [N], Mz [Nm] for patch length .18 m.
    [1, .06, 0, .8, 3392.7100793612667, 0, 0],
    [1, 0, .08, .8, 0, 3431.804606600746, -56.207519386762655],
    [1, .09, .12, .8, 2516.181689837825, 3354.908919783767, -26.871783524273358],
    [1, .2, -.3, .8, 2076.117366848113, -3114.176050272169, -47.71191633198063],
    [1, .8, 0, .8, 3205.96, 0, 0],
    [1, 0, 1.2, .8, 0, 3334.4, 0],
    [1, .07, .11, .4, 1053.475945891024, 1655.4622006858945, -16.643038550788496],
    [2, .06, 0, .8, 6696.171852598526, 0, 0],
    [2, 0, .08, .8, 0, 5682.111813028037, -119.83695755769742],
    [2, .09, .12, .8, 4680.019274413846, 6240.025699218462, -85.83983030006232],
    [2, .2, -.3, .8, 3953.632618977672, -5930.448928466508, -61.50462299771103],
    [2, .8, 0, .8, 6153.36, 0, 0],
    [2, 0, 1.2, .8, 0, 6186.88, 0],
    [2, .07, .11, .4, 1999.6732883253824, 3142.343738797029, -48.9817148013763],
  ])('matches independent scalar C++-equation fixture q=%s sx=%s sy=%s mu=%s', (q, sx, sy, mu, fx, fy, mz) => {
    const force = evaluateTMeasy(sx, sy, 4000 * q, 4000, { mu, contactPatchLength: .18 });
    expect(force.fx).toBeCloseTo(fx, 8);
    expect(force.fy).toBeCloseTo(fy, 8);
    expect(force.mz).toBeCloseTo(mz, 8);
  });

  it('differentiates the resultant angle and calibrated ellipse, not only radial slip', () => {
    const calibrations: TMeasyOptions[] = [
      {}, { mu: .4 }, { longitudinalScale: .65 },
      { longitudinalScale: 1.3, longitudinalSlipScale: .7, lateralSlipScale: 1.2, stiffnessScale: .8 },
    ];
    for (const options of calibrations) {
      for (const load of [2000, 4000, 8000, 14000, 20000]) {
        for (const sx of [-1.2, -.3, -.09, 0, .003, .07, .2, .7, 1.3]) {
          for (const sy of [-.4, -.11, 0, .08, .3, 1.2]) {
            const h = 1e-7;
            const f = evaluateTMeasy(sx, sy, load, 4000, options);
            const fd = (evaluateTMeasy(sx + h, sy, load, 4000, options).fx
              - evaluateTMeasy(sx - h, sy, load, 4000, options).fx) / (2 * h);
            expect(Math.abs(f.dfxDsx - fd) / Math.max(1, Math.abs(fd))).toBeLessThan(2e-5);
          }
        }
      }
    }
    expect(evaluateTMeasy(.3, 0, 4000, 4000).dfxDsx).toBeLessThan(0);
  });

  it('preserves force signs and combined-slip passivity in all quadrants', () => {
    for (const options of [{}, { mu: .2, longitudinalScale: .55 }, { mu: 1.3, stiffnessScale: 1.6 }]) {
      for (const sx of [-2, -.4, -.1, 0, .03, .2, 1.5]) {
        for (const sy of [-2, -.3, -.08, 0, .1, .4, 2]) {
          const f = evaluateTMeasy(sx, sy, 8000, 4000, options);
          expect(f.fx * sx).toBeGreaterThanOrEqual(0);
          expect(f.fy * sy).toBeGreaterThanOrEqual(0);
          expect(f.fx * sx + f.fy * sy).toBeGreaterThanOrEqual(0);
          expect(Object.values(f).every(Number.isFinite)).toBe(true);
        }
      }
    }
  });

  it('applies only explicit calibration and leaves defaults upstream-equivalent', () => {
    const normal = evaluateTMeasy(.07, .11, 4000, 4000);
    expect(evaluateTMeasy(.07, .11, 4000, 4000, {
      mu: .8, longitudinalScale: 1, longitudinalSlipScale: 1, lateralSlipScale: 1, stiffnessScale: 1,
    })).toEqual(normal);
    const ellipse = evaluateTMeasy(.07 * .6, .11, 4000, 4000, { longitudinalScale: .6 });
    expect(ellipse.fx).toBeCloseTo(normal.fx * .6, 10);
    expect(ellipse.fy).toBeCloseTo(normal.fy, 10);
    const x = guessPassCar70(4000, 4000).x;
    expect(evaluateTMeasy(x.sm * .7, 0, 4000, 4000, { longitudinalSlipScale: .7 }).fx).toBeCloseTo(x.fm, 9);
    expect(evaluateTMeasy(0, 0, 4000, 4000, { stiffnessScale: 1.2 }).dfxDsx).toBeCloseTo(x.df0 * 1.2, 9);
    // Friction changes peak slip as well as peak/sliding force, not df0.
    expect(evaluateTMeasy(x.sm * .5, 0, 4000, 4000, { mu: .4 }).fx).toBeCloseTo(x.fm * .5, 9);
    expect(evaluateTMeasy(0, 0, 4000, 4000, { mu: .4 }).dfxDsx).toBe(evaluateTMeasy(0, 0, 4000, 4000).dfxDsx);
  });

  it('returns no force and no NaN at zero load/friction or invalid inputs', () => {
    const zero = { fx: 0, fy: 0, mz: 0, dfxDsx: 0 };
    expect(evaluateTMeasy(.2, -.3, 4000, 4000, { mu: 0 })).toEqual(zero);
    expect(evaluateTMeasy(.2, -.3, 0, 4000)).toEqual(zero);
    expect(evaluateTMeasy(.2, -.3, -10, 4000)).toEqual(zero);
    expect(evaluateTMeasy(.2, -.3, 4000, 0)).toEqual(zero);
    expect(evaluateTMeasy(NaN, -.3, 4000, 4000)).toEqual(zero);
    expect(evaluateTMeasy(.2, Infinity, 4000, 4000)).toEqual(zero);
    expect(evaluateTMeasy(.2, -.3, 4000, 4000, { longitudinalScale: 0 })).toEqual(zero);
    expect(tmeasyCurve(.2, { ...twoParabolas, fm: 0 })).toEqual({ force: 0, forceOverSlip: 0, derivative: 0 });
    expect(tmeasyCurve(0, { ...twoParabolas, sm: 0 })).toEqual({ force: 0, forceOverSlip: 0, derivative: 0 });
    for (const mu of [1e-9, .01, .8]) {
      expect(Object.values(evaluateTMeasy(0, 0, 4000, 4000, { mu })).every(Number.isFinite)).toBe(true);
    }
  });

  it.each([
    [0, -64.08], [.08, -32.75682961591281], [.16337, 0],
    [.2, 10.870340851202075], [.5, 36.92477252593071], [.96524, 0], [1.5, 0],
  ])('ports the alignment trail, including reversal, at sy=%s', (sy, expected) => {
    expect(alignmentTorque(2000, sy, .18, .178, .16337, .96524)).toBeCloseTo(expected, 10);
    expect(alignmentTorque(-2000, -sy, .18, .178, .16337, .96524)).toBeCloseTo(-expected, 10);
    expect(alignmentTorque(2000, sy, 0, .178, .16337, .96524)).toBe(0);
  });

  it('has no mutable tire memory: interleaved calls replay bit-exactly', () => {
    const expected = evaluateTMeasy(.12, -.18, 5300, 4000, { contactPatchLength: .17 });
    const par = guessPassCar70(4000, 4000);
    par.x.fm = 0;
    for (let i = 0; i < 100; i++) evaluateTMeasy(i * .01, -.2, 3000 + 20 * i, 4000);
    expect(evaluateTMeasy(.12, -.18, 5300, 4000, { contactPatchLength: .17 })).toEqual(expected);
  });

  it('preserves the original dual-number kernel benchmark checksum', () => {
    // Recorded before scalar optimization; tolerate accumulated floating-point
    // roundoff only. Timing is measured separately, not asserted in CI.
    let checksum = 0;
    for (let i = 0; i < 100000; i++) {
      checksum += evaluateTMeasy((i % 100) / 100 - .5, -.2, 3700, 3700,
        { mu: .9, contactPatchLength: .14 }).fx;
    }
    expect(Math.abs(checksum - (-3323450.611765213))).toBeLessThan(1e-6);
  });
});
